/* The debug overlay's glyph atlas for the Linux build, drawn here on Windows exactly as
 * gpu_overlay.c draws it there (GDI, the same font and cells), and written out as a C header
 * (overlay_font.h, a build product - not kept in the repository).
 *
 * Usage: make_overlay_font <output header> */
#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <string.h>
#include <windows.h>

#define CELL_W 24
#define CELL_H 48
#define COLS 16
#define ATLAS_W (CELL_W * COLS)
#define ATLAS_H (CELL_H * 6)

int main(int argc, char **argv) {
    if (argc < 2) return 2;
    HDC dc = CreateCompatibleDC(NULL);
    BITMAPINFO bi;
    memset(&bi, 0, sizeof bi);
    bi.bmiHeader = (BITMAPINFOHEADER){sizeof(BITMAPINFOHEADER), ATLAS_W, -ATLAS_H, 1, 32, BI_RGB};
    void *bits = NULL;
    HBITMAP bmp = CreateDIBSection(dc, &bi, DIB_RGB_COLORS, &bits, NULL, 0);
    if (!bmp) return 1;
    SelectObject(dc, bmp);
    HFONT font = CreateFontW(-40, 0, 0, 0, FW_BOLD, 0, 0, 0, ANSI_CHARSET, OUT_DEFAULT_PRECIS, CLIP_DEFAULT_PRECIS, ANTIALIASED_QUALITY,
                             FIXED_PITCH | FF_MODERN, L"Consolas");
    SelectObject(dc, font);
    SetTextColor(dc, RGB(255, 255, 255));
    SetBkColor(dc, RGB(0, 0, 0));
    SetBkMode(dc, OPAQUE);
    for (int c = 32; c < 127; c++) {
        char ch = (char)c;
        TextOutA(dc, (c - 32) % COLS * CELL_W, (c - 32) / COLS * CELL_H + 2, &ch, 1);
    }
    GdiFlush();
    FILE *f = fopen(argv[1], "w");
    if (!f) return 1;
    fprintf(f, "/* Generated by tools/linux/make_overlay_font.c: %dx%d coverage, printable ASCII in %dx%d cells. */\n", ATLAS_W, ATLAS_H, CELL_W, CELL_H);
    fprintf(f, "static const unsigned char overlay_font[%d] = {\n", ATLAS_W * ATLAS_H);
    const unsigned *px = bits;
    for (int i = 0; i < ATLAS_W * ATLAS_H; i++) fprintf(f, "%u,%s", (px[i] >> 16) & 255, i % 32 == 31 ? "\n" : "");
    fprintf(f, "};\n");
    fclose(f);
    return 0;
}
